CREATE SEQUENCE T_SKJERMET_PERSON_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE T_SKJERMET_PERSON_FUNK_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE T_SKJERMET_PERSON (
    ID                  BIGINT      PRIMARY KEY,
    PERSONIDENT         CHAR(11)    NOT NULL,
    FUNKSJONELL_ID      BIGINT      NOT NULL        DEFAULT NEXTVAL('T_SKJERMET_PERSON_FUNK_SEQ'),
    SKJERMET_FOM        DATE        NOT NULL,
    SKJERMET_TOM        DATE,
    TILKNYTTET_RESSURS  CHAR(11),
    OPPRETTET_DATO      TIMESTAMP   NOT NULL,
    ENDRET_DATO         TIMESTAMP   NOT NULL
);
