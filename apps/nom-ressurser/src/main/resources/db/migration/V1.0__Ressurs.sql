CREATE SEQUENCE T_RESSURS_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE T_RESSURS (
    ID              BIGINT          PRIMARY KEY,
    NAVIDENT        CHAR(7)         NOT NULL,
    PERSONIDENT     CHAR(11)        NOT NULL,
    EPOST           VARCHAR(50),
    FORNAVN         VARCHAR(50)     NOT NULL,
    ETTERNAVN       VARCHAR(50)     NOT NULL,
    RESSURSTYPE     CHAR(11)        NOT NULL,
    STARTDATO       DATE            NOT NULL,
    SLUTTDATO       DATE,
    OPPRETTET_DATO  TIMESTAMP       NOT NULL,
    ENDRET_DATO     TIMESTAMP       NOT NULL,
    PRODUCED        BOOL            DEFAULT FALSE
);

CREATE TABLE T_OFFSET (
    OFFSET_NAME              CHAR(11)    PRIMARY KEY,
    OFFSET_VALUE             BIGINT      NOT NULL
);
INSERT INTO T_OFFSET (OFFSET_NAME, OFFSET_VALUE)
VALUES ('DVH_OFFSET', 0);

CREATE INDEX ressurs_person_ident_idx ON T_RESSURS(PERSONIDENT);
