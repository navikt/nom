CREATE TABLE T_RESSURS (
    ID              INTEGER PRIMARY KEY,
    PERSON_IDENT    VARCHAR(16) NOT NULL,
    STARTDATO       TIMESTAMP NOT NULL,
    SLUTTDATO       TIMESTAMP,
    OPPRETTET_DATO  TIMESTAMP NOT NULL,
    ENDRET_DATO     TIMESTAMP
);

CREATE SEQUENCE T_RESSURS_SEQ START WITH 1 INCREMENT BY 1;
CREATE INDEX ressurs_person_ident_idx ON T_RESSURS(PERSON_IDENT);
