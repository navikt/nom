CREATE SEQUENCE T_ENHET_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE T_ENHET (
    ID              BIGINT          PRIMARY KEY,
    ENHETSNR        BIGINT          NOT NULL,
    NAVN            VARCHAR(64)     NOT NULL,
    ENHETSTYPE      VARCHAR(16)     NOT NULL,
    AGRESSO_NR      VARCHAR(16)     NOT NULL,
    REMEDY_NR       VARCHAR(16)     NOT NULL,
    GYLDIG_FRA      DATE            NOT NULL,
    SLUTTDATO       DATE,
    OPPRETTET_AV    VARCHAR(16)     NOT NULL,
    OPPRETTET_DATO  TIMESTAMP       NOT NULL,
    ENDRET_AV       VARCHAR(16)     NOT NULL,
    ENDRET_DATO     TIMESTAMP       NOT NULL
);

CREATE SEQUENCE T_ORGANISERING_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE T_ORGANISERING (
    ID                  BIGINT          PRIMARY KEY,
    OVERENHET           BIGINT,
    UNDERENHET          BIGINT,
    ORGANISERINGSTYPE   VARCHAR(16),
    GYLDIG_FRA          DATE            NOT NULL,
    SLUTTDATO           DATE,
    OPPRETTET_AV        VARCHAR(16)     NOT NULL,
    OPPRETTET_DATO      TIMESTAMP       NOT NULL,
    ENDRET_AV           VARCHAR(16)     NOT NULL,
    ENDRET_DATO         TIMESTAMP       NOT NULL
);

