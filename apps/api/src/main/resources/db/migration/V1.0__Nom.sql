CREATE TABLE T_GENERIC_STORAGE (
    ID                  UUID        PRIMARY KEY,
    DATA_TYPE           TEXT        NOT NULL,
    DOCUMENT            JSONB       NOT NULL,
    STORED_DATE         TIMESTAMP   NOT NULL
);

CREATE INDEX DOCUMENT_INDEX ON T_GENERIC_STORAGE USING GIN (DOCUMENT);
CREATE INDEX FID_INDEX ON T_GENERIC_STORAGE USING BTREE ((DOCUMENT ->> 'fid'));
CREATE INDEX NAVIDENT_INDEX ON T_GENERIC_STORAGE USING BTREE ((DOCUMENT -> 'hendelseData' ->> 'navident'));
CREATE INDEX PERSONIDENT_INDEX ON T_GENERIC_STORAGE USING BTREE ((DOCUMENT -> 'hendelseData' ->> 'personident'));