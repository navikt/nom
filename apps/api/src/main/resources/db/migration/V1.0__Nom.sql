CREATE TABLE T_HENDELSER (
    HENDELSE_ID             UUID        PRIMARY KEY,
    FUNKSJONELL_ID          UUID        NOT NULL,
    FORESPORSEL_ID          UUID        NOT NULL,
    TIDLIGERE_ID            UUID,
    HENDELSE_TYPE           TEXT        NOT NULL,
    DATA_TYPE               TEXT        NOT NULL,
    DATA                    JSONB       NOT NULL,
    OPPRETTET_TIDSPUNKT     TIMESTAMP   NOT NULL
);

CREATE INDEX FUNKSJONELL_ID_INDEX ON T_HENDELSER (FUNKSJONELL_ID);
CREATE INDEX NAVIDENT_INDEX ON T_HENDELSER ((DATA->>'navIdent'));
CREATE INDEX PERSONIDENT_INDEX ON T_HENDELSER ((DATA->>'personIdent'));